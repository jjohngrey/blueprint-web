import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = process.argv[2] ? resolve(process.argv[2]) : root;
const kernel = await readFile(join(root, "lib/hairline/kernel.js"));
const kernelHash = createHash("sha256").update(kernel).digest("hex");
const originalKernelHash = "47ebec7647174e04e4f59c0305277c2a1dab83a763676946b17fa1694e7952fe";

if (kernelHash !== originalKernelHash) {
  throw new Error("The original Hairline kernel has changed. Restore lib/hairline/kernel.js before generating the runtime.");
}

const figures = [
  ["registrations", "badges-score/attendee-badges.js"],
  ["partners", "partners-faculty/partners-network.js"],
  ["satisfaction", "badges-score/feedback-token.js"],
  ["faculty", "partners-faculty/faculty-pie.js"],
  ["trophy", "awards-media/conference-trophy.js"],
  ["megaphone", "awards-media/social-megaphone.js"],
  ["television", "awards-media/news-television.js"],
  ["laptop", "awards-media/laptop.js"],
  ["billboard", "awards-media/billboard.js"],
  ["nfc", "awards-media/nfc-tap.js"],
];

const wrappedFigures = await Promise.all(figures.map(async ([variant, path]) => {
  const source = await readFile(join(sourceRoot, "public/hairline-impact", path), "utf8");
  const definition = source.match(/\bhairline\((\{[\s\S]*\})\);\s*$/);
  if (!definition || source.match(/\bhairline\(/g)?.length !== 1) {
    throw new Error(`Expected one final hairline definition in ${path}.`);
  }
  const body = `${source.slice(0, definition.index)}return (${definition[1]});`;
  return `  ${JSON.stringify(variant)}: (() => {\n${body}\n  })(),`;
}));

const runtime = `// Generated by scripts/build-hairline-runtime.mjs. Edit the figure sources, then regenerate.
// Hairline kernel: MIT, copyright (c) 2026 Lucas Marques. See ./LICENSE.
${kernel.toString("utf8")}

const figures = {
${wrappedFigures.join("\n")}
};

const cardEntryPoints = {
  registrations: [136, 142],
  partners: [151, 122],
  satisfaction: [139, 153],
  faculty: [117, 155],
  trophy: [252, 144],
  megaphone: [264, 150],
  television: [252, 91],
  nfc: [235, 154],
  laptop: [200, 160],
  billboard: [200, 160],
};

export function mountHairline({ variant, stage, svg }) {
  const definition = figures[variant];
  const read = document.createElement("span");
  const figure = definition.mount({ stage, svg, read }, definition.range[1]);
  const bag = HL.disposer();
  bag.add(figure.destroy);

  const card = stage.closest(".impact-card, .partner-benefit-card");
  if (card && variant !== "faculty") {
    const respond = () => {
      if (HL.reducedMotion()) return;
      const bounds = stage.getBoundingClientRect();
      const [x, y] = cardEntryPoints[variant];
      stage.dispatchEvent(new PointerEvent("pointermove", {
        pointerType: "mouse",
        clientX: bounds.left + bounds.width * x / 400,
        clientY: bounds.top + bounds.height * y / 320,
      }));
    };
    const reset = () => stage.dispatchEvent(new PointerEvent("pointerleave", { pointerType: "mouse" }));
    let previewTimer;
    const observer = new IntersectionObserver((entries) => {
      if (!entries.some(entry => entry.isIntersecting) || HL.reducedMotion()) return;
      observer.disconnect();
      stage.dataset.preview = "true";
      stage.dispatchEvent(new Event("hairline-preview"));
      if (!card.matches(":hover, :focus-within")) respond();
      previewTimer = setTimeout(() => {
        delete stage.dataset.preview;
        if (!card.matches(":hover, :focus-within")) reset();
      }, 1600);
    }, { threshold: 0.65 });
    observer.observe(stage);
    bag.add(() => { observer.disconnect(); clearTimeout(previewTimer); delete stage.dataset.preview; });

    bag.on(card, "pointerenter", (event) => {
      if (event.pointerType === "mouse") respond();
    });
    bag.on(card, "pointerleave", reset);
    bag.on(card, "focusin", respond);
    bag.on(card, "focusout", (event) => {
      if (!(event.relatedTarget instanceof Node) || !card.contains(event.relatedTarget)) reset();
    });
  }

  return { destroy: bag.dispose };
}
`;

const variants = figures.map(([variant]) => `  | ${JSON.stringify(variant)}`).join("\n");
const declarations = `// Generated by scripts/build-hairline-runtime.mjs.
export type HairlineVariant =
${variants};

export type HairlineMountOptions = {
  variant: HairlineVariant;
  stage: HTMLElement;
  svg: SVGSVGElement;
};

export type HairlineInstance = { destroy: () => void };

export function mountHairline(options: HairlineMountOptions): HairlineInstance;
`;

await Promise.all([
  writeFile(join(root, "lib/hairline/runtime.js"), runtime),
  writeFile(join(root, "lib/hairline/runtime.d.ts"), declarations),
]);

console.info(`Generated the shared runtime for ${figures.length} Hairline figures.`);
